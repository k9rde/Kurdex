    /**
     * Determines today's featured daily Dua based on the current date and optional manual shuffle offset.
     * Works 100% offline using deterministic date mathematics.
     */
    fun getDailyDuaForDate(calendar: Calendar = Calendar.getInstance(), shuffleOffset: Int = 0): DuaItem {
        val dayOfYear = calendar.get(Calendar.DAY_OF_YEAR)
        val dayOfWeek = calendar.get(Calendar.DAY_OF_WEEK)

        // If Friday and no manual shuffle, highlight Friday blessings or rotation
        if (dayOfWeek == Calendar.FRIDAY && shuffleOffset == 0) {
            val fridayItem = dailyDuasLibrary.find { it.id == "day_25" }
            if (fridayItem != null) return fridayItem
        }

        val total = dailyDuasLibrary.size
        val index = Math.floorMod(dayOfYear - 1 + shuffleOffset, total)
        return dailyDuasLibrary[index]
    }
